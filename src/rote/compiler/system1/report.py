"""The compile report, written by rote from data. No inference.

In ``--system1`` mode the agent does not write ``compile-report.md``. Every
section is something rote already knows: the decisions and their
confidence, the modules and their skill citations, the ``# rote:
assumption:`` markers the agent left in the code, the stubs. Writing it
deterministically removes a paid turn and the most common repair cause in
real compiles (an assumption with no Open questions entry): every marker
gets one, by construction.
"""

from __future__ import annotations

import re
from collections import Counter
from pathlib import Path

from rote.compiler.provenance import assumptions, citations
from rote.compiler.system1.decide import REVIEW_BELOW, Plan
from rote.compiler.system1.enforce import check_proposals
from rote.ir import Pipeline

_STUB = re.compile(r"raise\s+NotImplementedError\(\s*(?:f?[\"'])(.+?)[\"']", re.S)


def render(work_dir: Path, plan: Plan, pipeline: Pipeline, changes: list[str]) -> str:
    kinds = Counter(n.kind.value for n in pipeline.nodes)
    gates = [n for n in pipeline.nodes if n.kind.value == "hitl_gate"]
    lines = [
        f"# Compile report: {pipeline.name}",
        "",
        "Compiled with `--system1`: rote decided the structure with rules, and the agent "
        "wrote the implementations and judge prompts. This report is generated by rote.",
        "",
        "## Summary",
        "",
        f"- Nodes: {len(pipeline.nodes)} "
        f"({', '.join(f'{k} {v}' for k, v in sorted(kinds.items()))})",
        f"- Mandatory: {', '.join(f'`{n.id}`' for n in pipeline.nodes if n.mandatory) or 'none'}",
        f"- Fan-out: {', '.join(f'`{n.id}`' for n in pipeline.nodes if n.fan_out) or 'none'}",
        "- HITL gates: "
        + (
            ", ".join(
                f"`{g.id}` (signal `{g.signal}`, timeout {g.timeout or 'default'})" for g in gates
            )
            or "none"
        ),
        "",
        "## Crystallization log",
        "",
        "| node | kind | source section | module | skill citations |",
        "|---|---|---|---|---|",
    ]
    stubs: list[str] = []
    for n in pipeline.nodes:
        ref = n.impl or n.signature or ""
        path = work_dir / ref.split(":", 1)[0] if ref else None
        cited = 0
        if path is not None and path.is_file():
            source = path.read_text(encoding="utf-8", errors="replace")
            cited = len(citations(source))
            for m in _STUB.finditer(source):
                stubs.append(f"`{n.id}` is a stub: {' '.join(m.group(1).split())}")
        section = n.source.section if n.source else ""
        lines.append(f"| `{n.id}` | {n.kind.value} | {section} | `{ref}` | {cited} |")
    marked = assumptions(pipeline, work_dir)
    lines += ["", "## Open questions", ""]
    entries = [
        f"`{a.path}:{a.line}`{f' (`{a.node_id}`)' if a.node_id else ''}: assumed {a.text}"
        for a in marked
    ]
    entries += stubs
    entries += [f"System-1 decision below {REVIEW_BELOW} confidence: {r}" for r in plan.review]
    entries += [f"Proposed by the agent, not applied: {p}" for p in check_proposals(work_dir)]
    entries += [f"The agent edited a decision; rote restored it: {c}" for c in changes]
    lines += [f"- {e}" for e in entries] or ["- (none)"]
    lines += [
        "",
        "## Suggested next steps",
        "",
        "- Review every Open question above; each assumption is a rule the skill does not state.",
        "- Run the pipeline once (`rote run`) and compare it with a run of the skill itself.",
        "- Recompile with `rote compile --system1` after the skill changes: the decisions "
        "are deterministic, so only changed text costs tokens.",
        "",
    ]
    return "\n".join(lines)


def write(work_dir: Path, plan: Plan, pipeline: Pipeline, changes: list[str]) -> None:
    (work_dir / "compile-report.md").write_text(
        render(work_dir, plan, pipeline, changes), encoding="utf-8"
    )
